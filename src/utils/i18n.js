// 💡 多语言替换引擎：支持动态参数注入，例如 t(lang, 'groupCount', { count: 5 })
export function t(lang, key, params = {}) {
  const dict = translations[lang] || translations['zh-CN'];
  let val = dict[key] || translations['zh-CN'][key] || key;
  Object.keys(params).forEach(pKey => {
    val = val.replace(`{${pKey}}`, params[pKey]);
  });
  return val;
}